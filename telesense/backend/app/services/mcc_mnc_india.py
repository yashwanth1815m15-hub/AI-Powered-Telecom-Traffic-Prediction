def format_mcc_mnc_code(mcc: int, mnc: int) -> str:
    """Formats unmapped codes strictly as 'MCC xxx / MNC yy'."""
    mnc_str = f"{mnc:02d}" if 0 <= mnc < 100 else str(mnc)
    return f"MCC {mcc} / MNC {mnc_str}"


def lookup_operator(mcc: int, mnc: int) -> Optional[str]:
    """Returns cited operator name if present in the ITU-T E.212 / Wikipedia table, else None."""
    return INDIA_MCC_MNC_OPERATORS.get((int(mcc), int(mnc)))


def format_operator_label(mcc: int, mnc: int) -> str:
    """
    Returns operator name ONLY when (mcc, mnc) maps to it in the cited public list;
    otherwise strictly returns 'MCC xxx / MNC yy'.
    """
    op = lookup_operator(mcc, mnc)
    if op:
        return op
    return format_mcc_mnc_code(mcc, mnc)

