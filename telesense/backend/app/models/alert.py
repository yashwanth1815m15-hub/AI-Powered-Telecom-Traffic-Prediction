"""SQLAlchemy Models for Operational Alerts, Hysteresis Streaks, Audit Logs, and Recommendations."""

import datetime
from sqlalchemy import Column, String, Float, Integer, DateTime, ForeignKey, Text, UniqueConstraint
from sqlalchemy.orm import relationship
from app.database import Base


class Alert(Base):
    """Network Operations Center (NOC) event ticket for forecasted or live degradation."""
    __tablename__ = "alerts"

    id = Column(Integer, primary_key=True, autoincrement=True)
    tower_id = Column(String(32), ForeignKey("towers.tower_id"), nullable=False, index=True)
    alert_type = Column(String(32), nullable=False, default="PREDICTED_OVERLOAD", index=True)  # PREDICTED_OVERLOAD, WEAK_COVERAGE, OUTAGE, DEGRADED_SPEED
    created_at = Column(DateTime, default=datetime.datetime.utcnow, index=True)
    start_time = Column(DateTime, nullable=False)
    end_time = Column(DateTime, nullable=False)
    duration_hours = Column(Integer, default=1)
    peak_load_pct = Column(Float, nullable=False)
    severity = Column(String(32), nullable=False, index=True)  # WARNING, CRITICAL, OUTAGE
    reason = Column(Text, nullable=False)                      # Plain English summary
    mitigation_action = Column(Text, nullable=False)           # Playbook action
    status = Column(String(32), default="ACTIVE", index=True)  # ACTIVE, ACKNOWLEDGED, RESOLVED

    # Rich structured explanation & audit metadata
    what = Column(Text, nullable=True)
    where_location = Column(String(160), nullable=True)
    when_ist = Column(String(64), nullable=True)
    evidence_json = Column(Text, nullable=True)
    ranked_causes_json = Column(Text, nullable=True)
    expected_benefit = Column(Text, nullable=True)
    provenance = Column(String(32), nullable=False, default="SIMULATED")
    source = Column(String(16), nullable=False, default="baseline", index=True)  # baseline or demo
    acknowledged_at = Column(DateTime, nullable=True)
    resolved_at = Column(DateTime, nullable=True)

    tower = relationship("Tower", back_populates="alerts")


class AlertStreak(Base):
    """Tracks 3-consecutive-interval hysteresis & post-resolution cooldown per (tower_id, alert_type)."""
    __tablename__ = "alert_streaks"

    id = Column(Integer, primary_key=True, autoincrement=True)
    tower_id = Column(String(32), ForeignKey("towers.tower_id"), nullable=False, index=True)
    alert_type = Column(String(32), nullable=False, index=True)
    consecutive_breach_count = Column(Integer, default=0, nullable=False)
    consecutive_clear_count = Column(Integer, default=0, nullable=False)
    cooldown_until = Column(DateTime, nullable=True)
    updated_at = Column(DateTime, default=datetime.datetime.utcnow)

    __table_args__ = (
        UniqueConstraint("tower_id", "alert_type", name="uq_streak_tower_type"),
    )


class AlertAuditLog(Base):
    """Persistent NOC audit trail for alert lifecycle transitions (open / ack / resolve / auto-resolve)."""
    __tablename__ = "alert_audit_logs"

    id = Column(Integer, primary_key=True, autoincrement=True)
    alert_id = Column(Integer, nullable=True, index=True)
    tower_id = Column(String(32), nullable=False, index=True)
    alert_type = Column(String(32), nullable=False)
    action = Column(String(32), nullable=False)  # OPENED, ACKNOWLEDGED, RESOLVED, AUTO_RESOLVED
    actor = Column(String(64), nullable=False, default="system")
    note = Column(Text, nullable=True)
    timestamp = Column(DateTime, default=datetime.datetime.utcnow, index=True)


class Recommendation(Base):
    """Explainable infrastructure and spectrum investment advice generated by TeleSense."""
    __tablename__ = "recommendations"

    id = Column(Integer, primary_key=True, autoincrement=True)
    tower_id = Column(String(32), ForeignKey("towers.tower_id"), unique=True, nullable=False, index=True)
    action = Column(String(64), nullable=False, index=True)
    confidence_pct = Column(Float, default=95.0)
    reason = Column(Text, nullable=False)
    evidence_numbers = Column(Text, nullable=False)
    estimated_cost_inr = Column(Float, default=0.0)
    payback_months = Column(Integer, default=12)
    priority_rank = Column(Integer, default=3, index=True)
    updated_at = Column(DateTime, default=datetime.datetime.utcnow)

    tower = relationship("Tower", back_populates="recommendations")
